"""Check package imports, English documentation and isolated image contexts."""

import ast
from pathlib import Path
import re
import tempfile

from hermes_kubernetes.project.image_context import prepare


def check(root):
    root = Path(root)
    for path in (root / "hermes_kubernetes").rglob("*.py"):
        tree = ast.parse(path.read_text(), filename=str(path))
        for node in ast.walk(tree):
            names = (
                [node.module]
                if isinstance(node, ast.ImportFrom)
                else [alias.name for alias in node.names]
                if isinstance(node, ast.Import)
                else []
            )
            for name in names:
                if not name or not name.startswith("hermes_kubernetes."):
                    continue
                target = root.joinpath(*name.split("."))
                if (
                    not target.with_suffix(".py").is_file()
                    and not (target / "__init__.py").is_file()
                ):
                    raise ValueError(
                        f"Unresolved package import in {path.relative_to(root)}: {name}"
                    )
    for directory in ["docs", "skills"]:
        for path in (root / directory).rglob("*.md"):
            if re.search("[áãâéêíóõôúç]", path.read_text(), re.IGNORECASE):
                raise ValueError(f"Review documentation language: {path.relative_to(root)}")
    with tempfile.TemporaryDirectory(prefix="hermes-context-check-") as temporary:
        for component in ["hermes", "mcp"]:
            context = Path(temporary) / component
            prepare(root, context, component)
            for line in (context / "Dockerfile").read_text().splitlines():
                if not line.startswith("COPY ") or "--from=" in line:
                    continue
                for source in line.split()[1:-1]:
                    if source in {"source-provenance.json", "install-stamp.json"}:
                        continue  # Generated by the separately verified upstream build.
                    if not (context / source).exists():
                        raise ValueError(f"Missing {component} build input: {source}")
    print("Package imports, documentation and both image contexts validated; model_calls=0")


if __name__ == "__main__":
    check(Path(__file__).resolve().parents[2])
